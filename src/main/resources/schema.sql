-- outbox 表:通知投递记录
CREATE TABLE IF NOT EXISTS notification_record (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_uid    VARCHAR(36)  NOT NULL UNIQUE,
    event_type    VARCHAR(64)  NOT NULL,
    biz_id        VARCHAR(128) NOT NULL,
    payload       CLOB         NOT NULL,
    url           VARCHAR(512) NOT NULL,
    method        VARCHAR(16)  NOT NULL,
    headers       CLOB         NOT NULL,
    body          CLOB,
    status        VARCHAR(16)  NOT NULL,
    retry_count   INT          NOT NULL DEFAULT 0,
    next_retry_at BIGINT       NOT NULL DEFAULT 0,
    last_error    VARCHAR(1024),
    version       INT          NOT NULL DEFAULT 0,
    created_at    TIMESTAMP    NOT NULL,
    updated_at    TIMESTAMP    NOT NULL
);

-- 业务幂等:同一事件类型的同一业务键只允许提交一次
CREATE UNIQUE INDEX IF NOT EXISTS uk_event_biz ON notification_record (event_type, biz_id);

-- dispatcher 轮询热路径:按状态 + 到期时间取待投递记录
CREATE INDEX IF NOT EXISTS idx_status_retry ON notification_record (status, next_retry_at);
